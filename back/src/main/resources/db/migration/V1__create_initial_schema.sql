CREATE TABLE users (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR2(80) NOT NULL,
    last_name VARCHAR2(120) NOT NULL,
    birth_date DATE NOT NULL,
    document VARCHAR2(20) NOT NULL,
    email VARCHAR2(180) NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE soccer_fields (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(120) NOT NULL,
    active NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE reservation_slots (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_id NUMBER NOT NULL,
    start_time VARCHAR2(5) NOT NULL,
    end_time VARCHAR2(5) NOT NULL,
    price NUMBER(10, 2) NOT NULL,
    active NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE reservations (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    field_id NUMBER NOT NULL,
    slot_id NUMBER NOT NULL,
    reservation_date DATE NOT NULL,
    status VARCHAR2(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    canceled_at TIMESTAMP,
    active_field_id NUMBER
        GENERATED ALWAYS AS (
            CASE WHEN status = 'ACTIVE' THEN field_id ELSE NULL END
        ) VIRTUAL,
    active_reservation_date DATE
        GENERATED ALWAYS AS (
            CASE WHEN status = 'ACTIVE' THEN reservation_date ELSE NULL END
        ) VIRTUAL,
    active_slot_id NUMBER
        GENERATED ALWAYS AS (
            CASE WHEN status = 'ACTIVE' THEN slot_id ELSE NULL END
        ) VIRTUAL
);
